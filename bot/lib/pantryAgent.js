// chatId -> [{role, content}] — только "чистые" реплики (без внутренней tool_use возни),
// последние ~10 обменов. In-memory, сбрасывается при перезапуске процесса — тот же
// осознанный компромисс, что и awaitingNote в handlers/callbacks.js.
const chatHistories = new Map();
const MAX_HISTORY_TURNS = 10; // 10 пар user/assistant = 20 записей

function getHistory(chatId) {
  return chatHistories.get(chatId) || [];
}

// Фото в долгую память не складываем — иначе каждое следующее сообщение отправляло бы
// Claude все прошлые фото заново (дороже по токенам и раздувает контекст без пользы,
// т.к. что было на фото уже отражено в самой таблице после обработки).
function stripImages(content) {
  if (!Array.isArray(content)) return content;
  const hasImage = content.some(b => b.type === 'image');
  if (!hasImage) return content;
  const text = content.filter(b => b.type === 'text').map(b => b.text).join(' ');
  return [{ type: 'text', text: `[фото] ${text}`.trim() }];
}

function pushHistory(chatId, userContent, assistantReply) {
  const history = getHistory(chatId);
  history.push({ role: 'user', content: stripImages(userContent) }, { role: 'assistant', content: assistantReply });
  while (history.length > MAX_HISTORY_TURNS * 2) history.shift();
  chatHistories.set(chatId, history);
}

